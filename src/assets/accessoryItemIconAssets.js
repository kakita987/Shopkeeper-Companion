const ACCESSORY_ICON_BASENAME_OVERRIDES = new Map([
  ['accessory_amulet_t16_fellspectator.png', 'accessory_amulet_t16_fell_spectator.png'],
  ['accessory_amulet_t16_universaltranslator.png', 'accessory_amulet_t16_universal_translator.png'],
])

function toAccessoryRelativePath(legacyRelativePath) {
  const fileName = String(legacyRelativePath || '').split('/').pop()
  if (!fileName) {
    return ''
  }

  const resolvedFileName = ACCESSORY_ICON_BASENAME_OVERRIDES.get(fileName) || fileName
  return `./assets/Accessory/${resolvedFileName}`
}

